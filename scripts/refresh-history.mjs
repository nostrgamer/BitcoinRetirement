#!/usr/bin/env node
// Refresh the bundled price history from Coinbase daily closes, then regenerate the
// baseline constant used by the Netlify function and the historical stats shown in the UI.
// Run locally (roughly yearly): node scripts/refresh-history.mjs [--stats-only]
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CSV_PATH = path.join(ROOT, 'public', 'bitcoin-historical-data.csv');
const BASELINE_PATH = path.join(ROOT, 'netlify', 'functions', 'lib', 'baseline.js');
const STATS_PATH = path.join(ROOT, 'src', 'models', 'historicalStats.json');
const DAY_MS = 86400000;
const WINDOW_DAYS = 290; // Coinbase returns at most 300 candles per request
const GENESIS_MS = 1231006505000;

const fairValue = timestampMs =>
  10 ** (-16.509 + 5.690 * Math.log10(Math.max(1, (timestampMs - GENESIS_MS) / DAY_MS)));

const readCsv = () => fs.readFileSync(CSV_PATH, 'utf8').trim().split(/\r?\n/).slice(1).map(line => {
  const [date, price, timestamp] = line.split(',');
  return { date, price: Number(price), timestamp: Number(timestamp) };
});

async function fetchCandles(startMs, endMs) {
  const query = new URLSearchParams({
    granularity: '86400',
    start: new Date(startMs).toISOString(),
    end: new Date(endMs).toISOString()
  });
  const response = await fetch(`https://api.exchange.coinbase.com/products/BTC-USD/candles?${query}`, {
    headers: { Accept: 'application/json', 'User-Agent': 'BitcoinRetirement/1.0' }
  });
  if (!response.ok) throw new Error(`Coinbase HTTP ${response.status}`);
  const candles = await response.json();
  if (!Array.isArray(candles)) throw new Error('Unexpected Coinbase payload');
  return candles.map(c => ({ timestamp: Number(c[0]) * 1000, price: Number(c[4]) }));
}

async function refreshCsv(rows) {
  const lastMs = rows[rows.length - 1].timestamp;
  const now = new Date();
  const endMs = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), 1) - DAY_MS; // last day of previous month
  const added = new Map();
  for (let start = lastMs + DAY_MS; start <= endMs; start += WINDOW_DAYS * DAY_MS) {
    const windowEnd = Math.min(endMs, start + (WINDOW_DAYS - 1) * DAY_MS);
    for (const candle of await fetchCandles(start, windowEnd)) {
      if (candle.timestamp > lastMs && candle.timestamp <= endMs && Number.isFinite(candle.price) && candle.price > 0) {
        added.set(candle.timestamp, candle);
      }
    }
  }
  const newRows = [...added.values()].sort((a, b) => a.timestamp - b.timestamp).map(c => ({
    date: new Date(c.timestamp).toISOString().split('T')[0],
    price: Math.round(c.price * 100) / 100,
    timestamp: c.timestamp
  }));
  // Every day from the existing last row through endMs must be present. Appending past a gap
  // would advance the baseline and the gap would never be refilled.
  for (let day = lastMs + DAY_MS, i = 0; day <= endMs; day += DAY_MS, i += 1) {
    if (!newRows[i] || newRows[i].timestamp !== day) {
      throw new Error(`Missing Coinbase daily close for ${new Date(day).toISOString().split('T')[0]}; nothing written`);
    }
  }
  if (newRows.length > 0) {
    fs.appendFileSync(CSV_PATH, newRows.map(r => `\n${r.date},${r.price},${r.timestamp}`).join(''));
  }
  console.log(`Appended ${newRows.length} daily closes`);
}

// Definition (mirrored by src/models/historicalStats.test.ts): denominator = all CSV rows;
// ratio = price / fair value at the row timestamp; below = strictly < 1, above = strictly > 1.
function computeStats(rows) {
  const ratios = rows.map(r => ({ ratio: r.price / fairValue(r.timestamp), date: r.date }));
  const min = ratios.reduce((a, b) => (b.ratio < a.ratio ? b : a));
  const max = ratios.reduce((a, b) => (b.ratio > a.ratio ? b : a));
  const sorted = ratios.map(r => r.ratio).sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  const median = sorted.length % 2 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
  const pct = predicate => Math.round((ratios.filter(predicate).length / ratios.length) * 1000) / 10;
  const round2 = value => Math.round(value * 100) / 100;
  return {
    through: rows[rows.length - 1].date,
    observations: rows.length,
    minRatio: round2(min.ratio),
    minDate: min.date,
    maxRatio: round2(max.ratio),
    maxDate: max.date,
    medianRatio: round2(median),
    percentBelowFairValue: pct(r => r.ratio < 1),
    percentAboveFairValue: pct(r => r.ratio > 1)
  };
}

if (!process.argv.includes('--stats-only')) {
  await refreshCsv(readCsv());
}
const rows = readCsv();
const last = rows[rows.length - 1];
fs.writeFileSync(BASELINE_PATH, `'use strict';

// Generated by scripts/refresh-history.mjs — last date in public/bitcoin-historical-data.csv.
module.exports = {
  BASELINE_END: '${last.date}',
  BASELINE_END_MS: ${last.timestamp}
};
`);
// Content hash of the CSV; the client puts it in the CSV URL so any change bypasses browser caches.
const csvVersion = crypto.createHash('sha256').update(fs.readFileSync(CSV_PATH)).digest('hex').slice(0, 12);
const stats = { ...computeStats(rows), csvVersion };
fs.writeFileSync(STATS_PATH, JSON.stringify(stats, null, 2) + '\n');
console.log(stats);
